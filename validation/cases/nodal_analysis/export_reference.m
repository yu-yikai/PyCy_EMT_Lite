function export_reference(repositoryRoot)
%EXPORT_REFERENCE Run the unchanged MathWorks DC nodal-analysis circuit.
% Source: MathWorks-Teaching-Resources/DC-Circuit-Analysis, tag v2.2.2.
% Requires MATLAB, Simulink, Simscape and Simscape Electrical.
%   addpath('validation/cases/nodal_analysis'); export_reference(pwd)
if nargin == 0
    repositoryRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
end
referenceRoot = fullfile(repositoryRoot, 'local_reference', 'nodal_analysis');
previousFileGenConfig = Simulink.fileGenControl('getConfig');
cacheCleanup = onCleanup(@() Simulink.fileGenControl( ...
    'setConfig', 'config', previousFileGenConfig)); %#ok<NASGU>
Simulink.fileGenControl('set', 'CacheFolder', fullfile(referenceRoot, 'cache'), ...
    'CodeGenFolder', fullfile(referenceRoot, 'codegen'), 'createDir', true);
modelDirectory = fullfile(referenceRoot, 'simulink');
rawDirectory = fullfile(referenceRoot, 'raw_results');
normalizedDirectory = fullfile(referenceRoot, 'normalized_results');
for directory = {modelDirectory, rawDirectory, normalizedDirectory}
    if ~isfolder(directory{1}), mkdir(directory{1}); end
end
modelName = 'NodalAnalysisExample';
modelFile = fullfile(modelDirectory, [modelName '.slx']);
sourceURL = ['https://raw.githubusercontent.com/MathWorks-Teaching-Resources/' ...
    'DC-Circuit-Analysis/v2.2.2/Models/NodalAnalysisExample.slx'];
if ~isfile(modelFile), websave(modelFile, sourceURL); end
addpath(modelDirectory);
diary(fullfile(referenceRoot, 'export_reference.log'));
diaryCleanup = onCleanup(@() diary('off')); %#ok<NASGU>
fprintf('MATLAB: %s\nReference: %s\n', version, modelFile);
% Read the downloaded model; keep all physical component parameters intact.
if ~bdIsLoaded(modelName), open_system(modelFile); end
fprintf('Products: Simulink=%d Simscape=%d SimscapeElectrical=%d\n', ...
    license('test', 'Simulink'), license('test', 'Simscape'), ...
    license('test', 'Power_System_Blocks'));
in = Simulink.SimulationInput(modelName);
% The distributed example contains an unused, unconnected Virtual Multimeter.
% It is an isolated physical network without its own Solver Configuration and
% prevents compilation. Disable only this tool for the validation run; no
% terminal in the seven-resistor circuit is changed and the SLX is not saved.
multimeterBlock = Simulink.ID.getFullName([modelName ':204']);
in = in.setBlockParameter(multimeterBlock, 'Commented', 'on');
in = in.setModelParameter('StopTime', '0.01', 'Solver', 'ode15s', ...
    'RelTol', '1e-9', 'AbsTol', '1e-11', 'MaxStep', '1e-4', ...
    'EnablePacing', 'off', 'SimscapeLogType', 'all', ...
    'SimscapeLogName', 'simlog', 'SimscapeLogLimitData', 'off');
simulationTimer = tic;
out = sim(in);
elapsedSeconds = toc(simulationTimer);
disp(who(out));
save(fullfile(rawDirectory, 'simulink_output.mat'), 'out', '-v7.3');
% Nodal names are defined by the fixed physical terminal mapping:
% s=Vs.p=R1.p=R2.p; a=R2.n=R3.p=R4.p; b=R1.n=R3.n=R5.p=R6.p;
% c=R4.n=Is.p; d=Is.n=R5.n=R7.p; 0=Vs.n=R6.n=R7.n.
% Every branch current below is p->n. The Is parameter is +0.2 A n->p,
% hence its physical branch variable i must be -0.2 A p->n.
% Official convention: https://www.mathworks.com/help/simscape-electrical/ref/currentsource.html
assert(max(abs(out.simlog.Is.i.series.values('A') + 0.2)) < 1e-10);
physical = table(out.simlog.Vs.v.series.time, ...
    out.simlog.Vs.v.series.values('V'), ...
    out.simlog.Vs.v.series.values('V') - out.simlog.R2.v.series.values('V'), ...
    out.simlog.R6.v.series.values('V'), ...
    out.simlog.Vs.v.series.values('V') - out.simlog.R2.v.series.values('V') ...
        - out.simlog.R4.v.series.values('V'), ...
    out.simlog.R7.v.series.values('V'), ...
    out.simlog.R1.i.series.values('A'), out.simlog.R2.i.series.values('A'), ...
    out.simlog.R3.i.series.values('A'), out.simlog.R4.i.series.values('A'), ...
    out.simlog.R5.i.series.values('A'), out.simlog.R6.i.series.values('A'), ...
    out.simlog.R7.i.series.values('A'), out.simlog.Vs.i.series.values('A'), ...
    out.simlog.Is.i.series.values('A'), ...
    'VariableNames', {'time', 'v_src', 'v_a', 'v_b', 'v_c', 'v_d', ...
        'i_r1', 'i_r2', 'i_r3', 'i_r4', 'i_r5', 'i_r6', 'i_r7', 'i_vs', 'i_is'});
writetable(physical, fullfile(rawDirectory, 'simscape_native.csv'));
[~, lastIndex] = unique(physical.time, 'last');
physical = physical(lastIndex, :);
assert(all(diff(physical.time) > 0));
writetable(physical, fullfile(normalizedDirectory, 'reference.csv'));
metadata = struct('schema_version', 1, 'origin', 'MathWorks official teaching resource', ...
    'export_time_utc', char(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd HH:mm:ss Z')), ...
    'simulation_elapsed_seconds', elapsedSeconds, 'source_url', sourceURL, ...
    'repository_url', 'https://github.com/MathWorks-Teaching-Resources/DC-Circuit-Analysis', ...
    'source_tag', 'v2.2.2', 'model_name', modelName, 'matlab_version', version, ...
    'model_release', 'R2024a (exported from R2024b)', ...
    'required_products', {{'MATLAB', 'Simulink', 'Simscape', 'Simscape Electrical'}}, ...
    'solver', 'ode15s', 'relative_tolerance', 1e-9, 'absolute_tolerance', 1e-11, ...
    'maximum_step_s', 1e-4, 'stop_time_s', 0.01, ...
    'source_voltage_v', 3, 'current_source_n_to_p_a', 0.2, ...
    'resistances_ohm', [200 140 330 2000 330 50 50], ...
    'branch_current_convention', 'p to n; Is i=-0.2 A from c to d', ...
    'normalization', 'Absolute time; final sample at duplicate native times; node voltages reconstructed from exact branch-voltage identities.', ...
    'topology_changes', 'No change to the main electrical network; isolated unused Virtual Multimeter (SID 204) commented out in SimulationInput.', ...
    'parameter_changes', 'No electrical parameters changed; finite stop time, pacing disabled and logging/solver overrides.', ...
    'measurement_note', 'The original unconnected virtual multimeter has no Solver Configuration and blocks compilation. It is disabled only in the simulation input; original SLX remains unchanged.', ...
    'samples', height(physical), 'license', 'BSD-3-Clause at source tag v2.2.2', ...
    'redistribution', 'Third-party source model stays local; reproduce using the fixed-tag download URL.');
fid = fopen(fullfile(referenceRoot, 'provenance.json'), 'w', 'n', 'UTF-8');
assert(fid >= 0);
fprintf(fid, '%s\n', jsonencode(metadata, PrettyPrint=true));
fclose(fid);
fprintf('Exported %d real Simscape samples; node s,a,b,c,d at t=0:\n', height(physical));
disp(physical(1, {'v_src', 'v_a', 'v_b', 'v_c', 'v_d', 'i_is'}));
end
