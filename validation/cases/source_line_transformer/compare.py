"""Compare the full source-line-transformer network against native data."""

import hashlib
import json
import runpy
from pathlib import Path

from validation.common.runner import run_comparison


def _sha256(file: Path) -> str:
    with file.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def _lf_sha256(file: Path) -> str:
    return hashlib.sha256(file.read_bytes().replace(b"\r\n", b"\n")).hexdigest()


def check_reference_identity(directory: Path, reference_root: Path) -> None:
    """Reject stale canonical data before constructing/running a candidate."""
    manifest = json.loads((directory / "manifest.json").read_text(encoding="utf-8"))
    parameters = json.loads((directory / "parameters.json").read_text(encoding="utf-8"))
    provenance = json.loads((reference_root / "provenance.json").read_text(encoding="utf-8"))
    if (provenance["case_id"] != manifest["case_id"]
            or provenance["reference_id"] != manifest["reference_id"]):
        raise ValueError("Reference provenance belongs to a different case or original model")
    protocol = {entry["file"]: entry for entry in provenance["frozen_protocol"]}
    for name in ("manifest.json", "parameters.json", "acceptance_plan.md", "native_state_guard_addendum.md"):
        if _lf_sha256(directory / name) != protocol[name]["lf_sha256"]:
            raise ValueError(f"Reference uses a stale frozen protocol: {name}")
    if _lf_sha256(directory / "export_reference.m") != provenance["export_script_lf_sha256"]:
        raise ValueError("Reference was generated by a different export script")
    model = reference_root / "simulink" / manifest["reference_model"]
    model_hash = _sha256(model)
    if model_hash != provenance["model_sha256"] or model_hash != parameters["reference_model_sha256"]:
        raise ValueError("Canonical reference model bytes differ from the frozen original")
    if provenance["solver"] != parameters["reference_solver"]["solver"]:
        raise ValueError("Reference solver differs from the frozen protocol")
    if not provenance["reference_self_refinement"]["passed"]:
        raise ValueError("Native reference self-refinement did not pass")
    if len(provenance["runs"]) != 2 or {run["name"] for run in provenance["runs"]} != {"baseline", "refined"}:
        raise ValueError("Reference must contain both complete baseline and refined native runs")
    if not all(run["independent_accuracy"]["passed"] for run in provenance["runs"]):
        raise ValueError("Native reference absolute accuracy against independent physics did not pass")
    baseline_files = {entry["file"]: entry for entry in provenance["baseline_files"]}
    if _sha256(reference_root / "normalized_results/reference.csv") != baseline_files["reference.csv"]["sha256"]:
        raise ValueError("Canonical normalized reference differs from the archived native export")
    for name, entry in baseline_files.items():
        if _sha256(reference_root / "raw_results" / name) != entry["sha256"]:
            raise ValueError(f"Canonical raw native reference changed: {name}")


def main() -> None:
    directory = Path(__file__).resolve().parent
    repository = directory.parents[2]
    check_reference_identity(directory, repository / "local_reference/source_line_transformer")
    example = repository / "examples/25_source_line_transformer_network.py"
    case = runpy.run_path(str(example))["define_case"]()
    report = run_comparison(case, directory / "manifest.json", example)
    if not report["passed"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
