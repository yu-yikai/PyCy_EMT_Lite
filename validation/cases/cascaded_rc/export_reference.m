function export_reference(repositoryRoot)
%EXPORT_REFERENCE Run the unmodified MathWorks cascaded-RC physical network.
% Requires MATLAB, Simulink and Simscape R2025a or a compatible release.
% The original example stays local; this file contains only PyCy author code.
% From the repository root:
%   addpath('validation/cases/cascaded_rc'); export_reference(pwd)

if nargin == 0
    repositoryRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
end
referenceRoot = fullfile(repositoryRoot, 'local_reference', 'cascaded_rc');
previousFileGenConfig = Simulink.fileGenControl('getConfig');
cacheCleanup = onCleanup(@() Simulink.fileGenControl( ...
    'setConfig', 'config', previousFileGenConfig)); %#ok<NASGU>
Simulink.fileGenControl('set', 'CacheFolder', fullfile(referenceRoot, 'cache'), ...
    'CodeGenFolder', fullfile(referenceRoot, 'codegen'), 'createDir', true);
modelDirectory = fullfile(referenceRoot, 'simulink');
rawDirectory = fullfile(referenceRoot, 'raw_results');
normalizedDirectory = fullfile(referenceRoot, 'normalized_results');
directories = {modelDirectory, rawDirectory, normalizedDirectory};
for k = 1:numel(directories)
    if ~isfolder(directories{k}), mkdir(directories{k}); end
end
modelName = 'CascadedRCCircuitInSimulinkAndSimscape';
modelFile = fullfile(modelDirectory, [modelName '.slx']);
if ~isfile(modelFile)
    openExample('simscape/CascadedRCCircuitInSimulinkAndSimscapeExample', ...
        'workDir', modelDirectory);
end
addpath(modelDirectory);
diary(fullfile(referenceRoot, 'export_reference.log'));
diaryCleanup = onCleanup(@() diary('off')); %#ok<NASGU>
fprintf('MATLAB: %s\n', version);
fprintf('Reference: %s\n', modelFile);
fprintf('License Simulink=%d Simscape=%d\n', ...
    license('test', 'Simulink'), license('test', 'Simscape'));

% Fixed before inspecting PyCy comparisons. Solver and logging overrides do
% not alter the original model topology, parameters or initial conditions.
in = Simulink.SimulationInput(modelName);
in = in.setModelParameter('StopTime', '0.02', 'Solver', 'ode15s', ...
    'RelTol', '1e-8', 'AbsTol', '1e-10', 'MaxStep', '2e-6', ...
    'SignalLogging', 'on', 'SignalLoggingName', 'logsout', ...
    'SimscapeLogType', 'all', 'SimscapeLogName', 'simlog', ...
    'SimscapeLogLimitData', 'off');
simulationTimer = tic;
out = sim(in);
elapsedSeconds = toc(simulationTimer);
disp(who(out));
save(fullfile(rawDirectory, 'simulink_output.mat'), 'out', '-v7.3');

% All four physical-network signals share the same native variable-step grid.
assert(isequal(out.simlog.C1.v.series.time, out.simlog.C2.v.series.time));
assert(isequal(out.simlog.C1.v.series.time, out.simlog.R1.i.series.time));
assert(isequal(out.simlog.C1.v.series.time, out.simlog.R2.i.series.time));
physical = table(out.simlog.C1.v.series.time, ...
    out.simlog.C1.v.series.values, out.simlog.C2.v.series.values, ...
    out.simlog.R1.i.series.values, out.simlog.R2.i.series.values, ...
    'VariableNames', {'time', 'v_n1', 'v_n2', 'i_r1', 'i_r2'});
writetable(physical, fullfile(rawDirectory, 'simscape_native.csv'));
% Preserve original native samples above. For strict interpolation consumers,
% retain the last (post-event) sample at duplicate native time stamps.
[~, lastIndex] = unique(physical.time, 'last');
physical = physical(lastIndex, :);
assert(all(diff(physical.time) > 0));
writetable(physical, fullfile(normalizedDirectory, 'reference.csv'));

metadata = struct('schema_version', 1, 'origin', 'MathWorks official example', ...
    'export_time_utc', char(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd HH:mm:ss Z')), ...
    'simulation_elapsed_seconds', elapsedSeconds, ...
    'source_url', 'https://www.mathworks.com/help/simscape/ug/cascaded-rc-circuit-in-simulink-and-simscape.html', ...
    'example_id', 'simscape/CascadedRCCircuitInSimulinkAndSimscapeExample', ...
    'model_name', modelName, 'matlab_version', version, ...
    'model_release', 'R2025a Update 1 (downloaded by R2025a openExample)', ...
    'required_products', {{'MATLAB', 'Simulink', 'Simscape'}}, ...
    'solver', 'ode15s', 'relative_tolerance', 1e-8, ...
    'absolute_tolerance', 1e-10, 'maximum_step_s', 2e-6, ...
    'stop_time_s', 0.02, 'resistance_ohm', 10, ...
    'capacitance_f', 100e-6, 'capacitor_esr_ohm', 1e-6, ...
    'pulse_amplitude_v', 5, 'pulse_period_s', 0.01, ...
    'pulse_width_percent', 50, 'pulse_delay_s', 0.001, ...
    'capacitor_initial_voltage_v', 0, 'samples', height(physical), ...
    'normalization', 'No time shift; duplicate native times use final post-event sample.', ...
    'topology_changes', 'none', 'parameter_changes', 'none', ...
    'redistribution', 'Original MathWorks model and generated data remain local; no redistribution permission asserted.');
fid = fopen(fullfile(referenceRoot, 'provenance.json'), 'w', 'n', 'UTF-8');
assert(fid >= 0);
fprintf(fid, '%s\n', jsonencode(metadata, PrettyPrint=true));
fclose(fid);
fprintf('Exported %d actual Simscape samples to reference.csv\n', height(physical));
end
