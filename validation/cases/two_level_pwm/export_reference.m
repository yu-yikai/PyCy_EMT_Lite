function export_reference(repositoryRoot)
%EXPORT_REFERENCE Run the unmodified MathWorks three-phase two-level example.
% Requires MATLAB, Simulink, Simscape and Simscape Electrical. The original
% Spectrum Analyzer display can additionally require DSP System Toolbox.
%   addpath('validation/cases/two_level_pwm'); export_reference(pwd)
% No external gates, model edits, time shifts or fitted parameters are used.
if nargin == 0
    repositoryRoot=fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
end
referenceRoot=fullfile(repositoryRoot,'local_reference','two_level_pwm');
modelDirectory=fullfile(referenceRoot,'simulink');
rawDirectory=fullfile(referenceRoot,'raw_results');
normalizedDirectory=fullfile(referenceRoot,'normalized_results');
for directory={modelDirectory,rawDirectory,normalizedDirectory}
    if ~isfolder(directory{1}), mkdir(directory{1}); end
end
previousFileGenConfig=Simulink.fileGenControl('getConfig');
restore=onCleanup(@() Simulink.fileGenControl('setConfig','config',previousFileGenConfig)); %#ok<NASGU>
Simulink.fileGenControl('set','CacheFolder',fullfile(referenceRoot,'cache'), ...
    'CodeGenFolder',fullfile(referenceRoot,'codegen'),'createDir',true);
modelName='TwoLevelPWMGenerator';
modelFile=fullfile(modelDirectory,[modelName '.slx']);
if ~isfile(modelFile)
    openExample('simscapeelectrical/TwoLevelPWMGeneratorExample','workDir',modelDirectory);
end
addpath(modelDirectory);
diary(fullfile(referenceRoot,'export_reference.log'));
diaryCleanup=onCleanup(@() diary('off')); %#ok<NASGU>
fprintf('MATLAB: %s\nReference: %s\n',version,modelFile);
modelSHA256=sha256File(modelFile);
expectedSHA256='ad8ddf5e46dd633b4853d7694067528d5d20ce78a24059a2847c6a97dbc2ea34';
assert(strcmp(modelSHA256,expectedSHA256), ...
    'Official SLX hash differs from the inspected R2025a model. Inspect the new model and establish a new reference protocol before exporting.');
if ~bdIsLoaded(modelName), open_system(modelFile); end
actualModelPath=char(java.io.File(get_param(modelName,'FileName')).getCanonicalPath());
expectedModelPath=char(java.io.File(modelFile).getCanonicalPath());
assert(strcmpi(actualModelPath,expectedModelPath), ...
    'A different same-name model is loaded; close it without changing the reference model.');
assert(strcmp(get_param(modelName,'Dirty'),'off'), ...
    'The loaded model has unsaved changes; export only the inspected unmodified model.');
converter=Simulink.ID.getFullName([modelName ':1040']);
solver=Simulink.ID.getFullName([modelName ':1045']);
% TypeOptions ordering is not the enum's integer value. In R2025a the actual
% values are GTO=1, ideal=2, IGBT=3, MOSFET=4, thyristor=5, averaged=6.
assert(double(ee.enum.converters.switchingdevice.igbt)==3);
assert(str2double(get_param(converter,'device_type'))==3);
assert(strcmp(get_param(Simulink.ID.getFullName([modelName ':3879']),'sw'),'1'));
assert(strcmp(get_param(solver,'UseLocalSolver'),'on'));
assert(strcmp(get_param(solver,'LocalSolverChoice'),'NE_BACKWARD_EULER_ADVANCER'));

in=Simulink.SimulationInput(modelName);
% These variables equal the original PreLoadFcn (Ts=5e-6; fsw=1e3).
in=in.setVariable('Ts',5e-6);
in=in.setVariable('fsw',1e3);
in=in.setModelParameter('StopTime','0.2','SimscapeLogType','all', ...
    'SimscapeLogName','simlog','SimscapeLogLimitData','off');
simulationTimer=tic;
out=sim(in);
elapsedSeconds=toc(simulationTimer);
save(fullfile(rawDirectory,'simulink_output.mat'),'out','-v7.3');

% Official plotting code uses these exact phase_splitter current logs.
% XML connectivity and the positive current after phase-a's upper switch
% closes confirm the direction is converter/source -> RL load.
physical=table(out.simlog.Converter.phase_splitter.i_a.series.time, ...
    out.simlog.Converter.phase_splitter.i_a.series.values('A'), ...
    out.simlog.Converter.phase_splitter.i_b.series.values('A'), ...
    out.simlog.Converter.phase_splitter.i_c.series.values('A'), ...
    'VariableNames',{'time','i_a','i_b','i_c'});
writetable(physical,fullfile(rawDirectory,'simscape_native.csv'));
[~,lastIndex]=unique(physical.time,'last');
physical=physical(lastIndex,:);
assert(all(diff(physical.time)>0));
writetable(physical,fullfile(normalizedDirectory,'reference.csv'));

% Audit the real physical gate voltages, not a recreated or externally fed
% pulse train. vce identities establish Q1/2=A upper/lower, Q3/4=B, Q5/6=C.
gates=table(out.simlog.Converter.Q1.G.series.time,'VariableNames',{'time'});
for k=1:6
    name=['Q' num2str(k)];
    gates.([name '_gate'])=out.simlog.Converter.(name).G.series.values('V');
    gates.([name '_vce'])=out.simlog.Converter.(name).vce.series.values('V');
    gates.([name '_ice'])=out.simlog.Converter.(name).ice.series.values('A');
    gates.([name '_diode_i'])=out.simlog.Converter.(name).diode.i.series.values('A');
end
writetable(gates,fullfile(rawDirectory,'physical_device_gates.csv'));
assert(all((gates.Q1_gate>.5)~=(gates.Q2_gate>.5)));
assert(all((gates.Q3_gate>.5)~=(gates.Q4_gate>.5)));
assert(all((gates.Q5_gate>.5)~=(gates.Q6_gate>.5)));
powerAudit=table(physical.time, ...
    sum([out.simlog.Converter.phase_splitter.a.v.series.values('V'), ...
         out.simlog.Converter.phase_splitter.b.v.series.values('V'), ...
         out.simlog.Converter.phase_splitter.c.v.series.values('V')].* ...
         [physical.i_a,physical.i_b,physical.i_c],2), ...
    physical.i_a.^2+physical.i_b.^2+physical.i_c.^2, ...
    'VariableNames',{'time','p_load_terminal','p_load_resistive'});
% Terminal power uses pole voltages relative to DC negative. The floating
% star has zero sum of currents, so the common potential cancels in sum(v*i).
writetable(powerAudit,fullfile(rawDirectory,'load_power_audit.csv'));

metadata=struct('schema_version',1,'origin','MathWorks official example, unmodified circuit and controller', ...
    'export_time_utc',char(datetime('now','TimeZone','UTC','Format','yyyy-MM-dd HH:mm:ss Z')), ...
    'source_url','https://www.mathworks.com/help/simscape-electrical/ug/three-phase-two-level-pwm-generator.html', ...
    'example_id','simscapeelectrical/TwoLevelPWMGeneratorExample', ...
    'model_name',modelName,'matlab_version',version,'simulation_elapsed_seconds',elapsedSeconds, ...
    'model_release','R2025a Update 1 (downloaded by R2025a openExample)', ...
    'required_products',{{'MATLAB','Simulink','Simscape','Simscape Electrical','DSP System Toolbox (original Spectrum Analyzer display)'}}, ...
    'model_md5',Simulink.getFileChecksum(modelFile), ...
    'model_sha256',modelSHA256, ...
    'solver',get_param(modelName,'Solver'),'local_solver','Backward Euler', ...
    'local_solver_step_s',5e-6,'local_solver_residual_tolerance',1e-9,'stop_time_s',.2, ...
    'dc_voltage_v',400,'dc_connection','Stiff ideal source directly across converter DC terminals; no series DC resistor, capacitor or filter.', ...
    'frequency_hz',60,'switching_frequency_hz',1000,'modulation_index',.8, ...
    'reference_phase_offsets_rad',[0,-2*pi/3,2*pi/3]+pi/2,'reference_hold_s',1e-4, ...
    'rate_transition',struct('Integrity','on','Deterministic','on','InitialCondition','0','OutPortSampleTime',1e-4), ...
    'pwm',struct('mode','CPWM/SPWM','sampling','Natural','sample_s',5e-6, ...
        'algorithm','Official block calculates switching times; it is not a direct carrier comparator. Native physical gate logs preserved.'), ...
    'load',struct('structure','Series RL, floating wye','resistance_ohm',1,'inductance_h',.001, ...
        'initial_current_a',[0,0,0],'G_parasitic_parameter_s',1e-6), ...
    'converter',struct('enum_value',3,'device','IGBT (ideal, switching)', ...
        'forward_voltage_v',.8,'on_resistance_ohm',.001,'off_conductance_s',1e-5, ...
        'gate_threshold_v',.5,'protection_diode','No dynamics','diode_forward_voltage_v',.8, ...
        'diode_on_resistance_ohm',.001,'diode_off_conductance_s',1e-5,'snubber','none','thermal','off'), ...
    'gate_mapping','Q1/Q2 = A upper/lower; Q3/Q4 = B upper/lower; Q5/Q6 = C upper/lower. Native 0/1V gate pairs are strictly complementary at every logged time.', ...
    'signal_mapping',struct('i_a','Converter.phase_splitter.i_a','i_b','Converter.phase_splitter.i_b','i_c','Converter.phase_splitter.i_c'), ...
    'current_convention','Converter/source to RL load; positive absorption.', ...
    'equivalence_boundary','IGBT forward drop, unidirectional channel and reverse-current diodes differ from PyCy bilateral Ron switches. This is a fixed-criteria steady-state waveform/fundamental comparison, not device/diode validation.', ...
    'normalization','Native timestamps and currents retained; last sample at duplicate times, no fitting, shift, scaling or resampling.', ...
    'topology_changes','none','parameter_changes','No physical/control changes; Ts, fsw and stop time explicitly equal original defaults.', ...
    'samples',height(physical),'redistribution','MathWorks model/scripts and generated data remain local; no redistribution permission asserted.');
fid=fopen(fullfile(referenceRoot,'provenance.json'),'w','n','UTF-8');
assert(fid>=0); fprintf(fid,'%s\n',jsonencode(metadata,PrettyPrint=true)); fclose(fid);
fprintf('Exported %d real Simscape samples; physical gates and power audit preserved.\n',height(physical));
end

function checksum=sha256File(fileName)
fid=fopen(fileName,'rb');
assert(fid>=0,'Cannot read model file for SHA-256 verification.');
cleanup=onCleanup(@() fclose(fid)); %#ok<NASGU>
bytes=fread(fid,Inf,'*uint8');
digest=java.security.MessageDigest.getInstance('SHA-256');
digest.update(typecast(bytes,'int8'));
checksum=lower(reshape(dec2hex(typecast(digest.digest(),'uint8'),2).',1,[]));
end
