function export_reference(repositoryRoot)
%EXPORT_REFERENCE Run the unmodified official earthing-effects physical model.
% Requires MATLAB, Simulink, Simscape and Simscape Electrical.
%   addpath('validation/cases/earthing'); export_reference(pwd)
% The original plot script swaps the two current-group labels. This exporter
% maps sensors from the actual electrical connections and preserves both the
% original plotting source and its label mapping as local audit evidence.
if nargin == 0
    repositoryRoot = fileparts(fileparts(fileparts(fileparts(mfilename('fullpath')))));
end
referenceRoot = fullfile(repositoryRoot, 'local_reference', 'earthing');
previousFileGenConfig = Simulink.fileGenControl('getConfig');
cacheCleanup = onCleanup(@() Simulink.fileGenControl( ...
    'setConfig', 'config', previousFileGenConfig)); %#ok<NASGU>
Simulink.fileGenControl('set', 'CacheFolder', fullfile(referenceRoot, 'cache'), ...
    'CodeGenFolder', fullfile(referenceRoot, 'codegen'), 'createDir', true);
modelDirectory = fullfile(referenceRoot, 'simulink');
rawDirectory = fullfile(referenceRoot, 'raw_results');
normalizedDirectory = fullfile(referenceRoot, 'normalized_results');
for directory = {modelDirectory, rawDirectory, normalizedDirectory}
    if ~isfolder(directory{1}), mkdir(directory{1}); end
end
modelName = 'EarthingEffects';
modelFile = fullfile(modelDirectory, [modelName '.slx']);
if ~isfile(modelFile)
    openExample('simscapeelectrical/EarthingEffectsExample', ...
        'workDir', modelDirectory);
end
addpath(modelDirectory);
diary(fullfile(referenceRoot, 'export_reference.log'));
diaryCleanup = onCleanup(@() diary('off')); %#ok<NASGU>
fprintf('MATLAB: %s\nReference: %s\n', version, modelFile);
if ~bdIsLoaded(modelName), open_system(modelFile); end
% The downloaded example has three independent physical networks (grounded,
% floating star and each phase open); all retain their native local BE solver.
solverBlock = Simulink.ID.getFullName([modelName ':72']);
assert(strcmp(get_param(solverBlock, 'UseLocalSolver'), 'on'));
assert(abs(str2double(get_param(solverBlock, 'LocalSolverSampleTime')) - 1e-4) < 1e-15);

in = Simulink.SimulationInput(modelName);
in = in.setModelParameter('StopTime', '0.1', ...
    'SimscapeLogType', 'all', 'SimscapeLogName', 'simlog', ...
    'SimscapeLogLimitData', 'off', 'SignalLoggingName', 'logsout');
simulationTimer = tic;
out = sim(in);
elapsedSeconds = toc(simulationTimer);
save(fullfile(rawDirectory, 'simulink_output.mat'), 'out', '-v7.3');

% XML connectivity at the model root, checked before constructing PyCy:
% grounded: source SID74 -> current sensor vi SID150 -> load SID160;
%           phase-voltage sensor vi1 SID169 connects across that load.
% floating: source SID217 -> current sensor vi2 SID189 -> load SID205;
%           phase-voltage sensor vi3 SID198 connects across that load.
% Currents are source-to-load. Each V_output is a vector of three phase
% differences across the load resistors, not three line-to-line voltages.
% Grounded voltages are relative to 0; floating voltages relative to the
% shared ungrounded star point. The two ideal sources are identical, so
% v_neutral = grounded phase-a voltage - floating phase-a load voltage.
physical = table(out.simlog.Sensing_vi1.Phase_Voltage_Sensor.V_output.series.time, ...
    out.simlog.Sensing_vi1.Phase_Voltage_Sensor.V_output.series.values('V'), ...
    out.simlog.Sensing_vi3.Phase_Voltage_Sensor.V_output.series.values('V'), ...
    out.simlog.Sensing_vi.Current_Sensor.I_output.series.values('A'), ...
    out.simlog.Sensing_vi2.Current_Sensor.I_output.series.values('A'), ...
    'VariableNames', {'time', 'v_grounded', 'v_floating', 'i_grounded', 'i_floating'});
physical.v_neutral = physical.v_grounded(:, 1) - physical.v_floating(:, 1);
writetable(physical, fullfile(rawDirectory, 'simscape_native.csv'));

% Preserve the *official plot script's* erroneous current-group assignments,
% separately from the correctly mapped numerical reference. These values are
% still real logs; only the column labels in this evidence file are wrong.
officialPlotLabels = table(physical.time, physical.v_grounded, physical.v_floating, ...
    physical.i_floating, physical.i_grounded, ...
    'VariableNames', {'time', 'v_grounded', 'v_floating', 'i_grounded', 'i_floating'});
writetable(officialPlotLabels, fullfile(rawDirectory, 'official_plot_label_mapping.csv'));
plotSource = fullfile(modelDirectory, 'EarthingEffectsPlotResults.m');
copyfile(plotSource, fullfile(rawDirectory, 'EarthingEffectsPlotResults.m'));
[~, lastIndex] = unique(physical.time, 'last');
physical = physical(lastIndex, :);
assert(all(diff(physical.time) > 0));
writetable(physical, fullfile(normalizedDirectory, 'reference.csv'));

metadata = struct('schema_version', 1, 'origin', 'MathWorks official example, unmodified physical model', ...
    'export_time_utc', char(datetime('now', 'TimeZone', 'UTC', 'Format', 'yyyy-MM-dd HH:mm:ss Z')), ...
    'simulation_elapsed_seconds', elapsedSeconds, ...
    'source_url', 'https://www.mathworks.com/help/simscape-electrical/ug/earthing-effects.html', ...
    'example_id', 'simscapeelectrical/EarthingEffectsExample', ...
    'model_name', modelName, 'matlab_version', version, ...
    'model_release', 'R2025a Update 1 (downloaded by R2025a openExample)', ...
    'required_products', {{'MATLAB', 'Simulink', 'Simscape', 'Simscape Electrical'}}, ...
    'solver', get_param(modelName, 'Solver'), 'relative_tolerance', 1e-3, ...
    'absolute_tolerance', 1e-3, 'local_solver', 'Backward Euler', ...
    'local_solver_step_s', 1e-4, 'local_solver_residual_tolerance', 1e-9, ...
    'stop_time_s', 0.1, 'source_phase_peak_v', 100, 'frequency_hz', 60, ...
    'source_waveform', '100*sin(2*pi*60*t + [0,-2*pi/3,+2*pi/3]); ideal grounded source neutral', ...
    'initial_resistances_ohm', [1 1 1], ...
    'phase_a_event', struct('time_s', 0.05, 'resistance_after_ohm', 3), ...
    'phase_c_event', struct('time_s', 0.07, 'resistance_after_ohm', 1.5), ...
    'voltage_convention', 'v_grounded is phase minus ground; v_floating is phase minus common floating star; v_neutral reconstructed from identical ideal source phase-a voltages.', ...
    'current_convention', 'Source to load for each phase.', ...
    'signal_mapping', struct( ...
        'v_grounded', 'Sensing_vi1.Phase_Voltage_Sensor.V_output', ...
        'v_floating', 'Sensing_vi3.Phase_Voltage_Sensor.V_output', ...
        'i_grounded', 'Sensing_vi.Current_Sensor.I_output', ...
        'i_floating', 'Sensing_vi2.Current_Sensor.I_output'), ...
    'plot_script_issue', 'Official script assigns Igrounding=vi2 and Ifloating=vi; actual connections require the reverse grouping. Original source and label mapping preserved in raw_results.', ...
    'source_file_md5', struct('model', Simulink.getFileChecksum(modelFile), ...
        'plot_script', Simulink.getFileChecksum(plotSource)), ...
    'normalization', 'No fitted time shift, scaling or resampling; last sample at duplicate native times. Matrix CSV columns use suffixes _1,_2,_3 = phases a,b,c.', ...
    'topology_changes', 'none', 'parameter_changes', 'none', ...
    'scope_note', 'Original open-circuit third group runs in the reference but is not included in this teaching comparison.', ...
    'samples', height(physical), ...
    'redistribution', 'Original MathWorks model, source scripts and generated data stay local; no redistribution permission asserted.');
fid = fopen(fullfile(referenceRoot, 'provenance.json'), 'w', 'n', 'UTF-8');
assert(fid >= 0);
fprintf(fid, '%s\n', jsonencode(metadata, PrettyPrint=true));
fclose(fid);
fprintf('Exported %d actual Simscape samples with topology-correct labels.\n', height(physical));
end
